HELP_TEXT = FAQ_ENTRIES[0][2]


def match_faq(text: str, threshold: float = 0.5) -> FaqHit | None:
    q = text.lower().strip()
    if not q:
        return None
    best: FaqHit | None = None
    for key, keywords, answer in FAQ_ENTRIES:
        hits = sum(1 for kw in keywords if kw in q)
        score = hits / max(1, len(keywords) * 0.35)
        # Нормируем грубо: хотя бы одно ключевое слово
        if hits == 0:
            continue
        score = min(1.0, 0.4 + 0.3 * hits)
        if best is None or score > best.score:
            best = FaqHit(key=key, answer=answer, score=score)
    if best and best.score >= threshold:
        return best
    return None
